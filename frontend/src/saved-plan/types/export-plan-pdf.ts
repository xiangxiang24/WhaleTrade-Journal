import { ASSET_BY_ID } from '../../shared/data/assets'
import type { CalcOutput, CalcPlan } from '../../shared/types/calc-plan'
import { formatBaht, formatPercent } from '../../target-amount/types/format'
import { stageName } from '../../target-amount/types/target-amount'
import { formatYears, planYears } from './saved-plan'

/** กันข้อความที่ผู้ใช้พิมพ์เอง (ชื่อแผน ชื่อพอร์ต) หลุดเป็น HTML */
const esc = (value: string) =>
  value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

const STYLE = `
  @page { size: A4; margin: 18mm; }
  * { box-sizing: border-box; }
  body { margin: 0; color: #0f2747; font: 13px/1.5 "Helvetica Neue", Helvetica, "Thonburi", "Sukhumvit Set", sans-serif; }
  .eyebrow { font-size: 11px; font-weight: 600; letter-spacing: .08em; color: #5b6b82; text-transform: uppercase; }
  h1 { margin: 4px 0 0; font-size: 26px; }
  .sub { margin: 2px 0 0; color: #35507a; }
  .hero { margin-top: 22px; padding: 18px 22px; border-radius: 16px; background: #eef4ff; }
  .hero .amount { margin: 2px 0 0; font-size: 34px; font-weight: 700; }
  .hero .note { margin: 4px 0 0; color: #35507a; }
  .bar { display: flex; height: 10px; margin-top: 14px; overflow: hidden; border-radius: 5px; background: #dbe7fb; }
  .legend { display: flex; gap: 18px; margin-top: 8px; font-size: 11px; color: #35507a; }
  .dot { display: inline-block; width: 8px; height: 8px; margin-right: 5px; border-radius: 4px; }
  h2 { margin: 24px 0 6px; font-size: 14px; }
  table { width: 100%; border-collapse: collapse; }
  td, th { padding: 7px 0; border-bottom: 1px solid #e2e8f2; text-align: left; font-weight: 400; }
  td:last-child, th:last-child { text-align: right; }
  th { font-size: 11px; color: #5b6b82; font-weight: 600; }
  tr.total td { border-bottom: 0; font-size: 15px; font-weight: 700; }
  .foot { margin-top: 26px; font-size: 11px; color: #5b6b82; }
`

const row = (label: string, value: string) => `<tr><td>${esc(label)}</td><td>${esc(value)}</td></tr>`

/** หน้ารายงานของแผน (HTML ล้วน ไม่มีสคริปต์/ลิงก์ภายนอก) ใช้พิมพ์เป็น PDF ใน Electron */
export function buildPlanReportHtml(plan: CalcPlan, source: string, output: CalcOutput, savedDate: string) {
  const bar = (share: number, color: string) => `<div style="width:${share}%;background:${color}"></div>`
  const phases = plan.phases.map((phase, index) =>
    row(
      `Phase ${index + 1} (${stageName(index)}): ${formatYears(phase.years)} × ${formatBaht(phase.monthlyDca)} THB/month`,
      `${formatBaht(output.phaseTotals[index] ?? 0)} THB`,
    ),
  )
  const assets = plan.assets.map((asset) =>
    row(ASSET_BY_ID.get(asset.assetId)?.ticker ?? String(asset.assetId), `${asset.dividendPct}% / year`),
  )
  return `<!doctype html><html><head><meta charset="utf-8"><title>${esc(plan.name)}</title><style>${STYLE}</style></head><body>
  <div class="eyebrow">Whale Trade Journal · Plan report</div>
  <h1>${esc(plan.name)}</h1>
  <p class="sub">${esc(source)} · ${esc(formatYears(planYears(plan)))} · ${esc(savedDate)}</p>
  <div class="hero">
    <div class="eyebrow">Expected amount at the end</div>
    <p class="amount">${formatBaht(output.total)} THB</p>
    <p class="note">+${formatBaht(output.dividends)} THB (+${formatPercent(output.increasePct)}) generated by dividend compounding</p>
    <div class="bar">${bar(output.shares.principal, '#9dbdf0')}${bar(output.shares.dca, '#3b6fd4')}${bar(output.shares.dividends, '#3fa66b')}</div>
    <div class="legend">
      <span><i class="dot" style="background:#9dbdf0"></i>Initial principal ${formatPercent(output.shares.principal)}</span>
      <span><i class="dot" style="background:#3b6fd4"></i>DCA ${formatPercent(output.shares.dca)}</span>
      <span><i class="dot" style="background:#3fa66b"></i>Dividends ${formatPercent(output.shares.dividends)}</span>
    </div>
  </div>
  <h2>Estimate</h2>
  <table>
    ${row('Initial principal', `${formatBaht(plan.principal)} THB`)}
    ${phases.join('')}
    ${row('Total invested capital', `${formatBaht(output.totalInvested)} THB`)}
    ${row('Expected dividends (reinvested)', `+${formatBaht(output.dividends)} THB`)}
    <tr class="total"><td>Total Estimated Value</td><td>${formatBaht(output.total)} THB</td></tr>
  </table>
  ${assets.length ? `<h2>Dividend yield assumptions</h2><table>${assets.join('')}</table>` : ''}
  <p class="foot">An illustrative model, not a forecast or guarantee of actual investment returns.</p>
  </body></html>`
}

/** ส่งออกเป็น PDF ผ่านหน้าต่างพิมพ์ของ Electron (ผู้ใช้เลือกที่บันทึกเอง) คืน false ถ้ากดยกเลิก */
export async function exportPlanPdf(plan: CalcPlan, source: string, output: CalcOutput, savedDate: string, filename: string) {
  const app = window.whaleApp
  if (!app) throw new Error('PDF export is only available in the desktop app.')
  const result = await app.exportPdf(buildPlanReportHtml(plan, source, output, savedDate), filename)
  if ('error' in result) throw new Error('Could not create the PDF. Please try again.')
  return !('canceled' in result)
}
