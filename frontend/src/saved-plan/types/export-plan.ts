import { ASSET_BY_ID } from '../../shared/data/assets'
import type { CalcPlan } from '../../shared/types/calc-plan'
import type { CalcOutput } from '../../shared/types/calc-plan'
import { CSV_BOM, cell, downloadCsv } from '../../transaction-logs/types/export-csv'
import { formatBaht, formatPercent } from '../../target-amount/types/format'
import { stageName } from '../../target-amount/types/target-amount'
import { formatYears, planYears } from './saved-plan'

/** ชื่อไฟล์ที่ปลอดภัยจากชื่อแผน เช่น "Retire at 60" → "retire-at-60-plan.csv" */
export function planFilename(name: string, extension: 'csv' | 'png') {
  const slug = name.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, '-').replace(/^-+|-+$/g, '')
  return `${slug || 'saved'}-plan.${extension}`
}

/** สร้างข้อความ CSV ของแผน: ข้อมูลทั่วไป / ค่าที่ใช้คำนวณ (เงินต้น เฟส หุ้น) / ผลประมาณการ (UTF-8 BOM ให้ภาษาไทยเปิดใน Excel ได้) */
export function buildPlanCsv(plan: CalcPlan, source: string, output: CalcOutput) {
  const rows: (string | number)[][] = [
    ['Section', 'Item', 'Value'],
    ['Plan', 'Name', plan.name],
    ['Plan', 'Saved date', plan.savedAt.slice(0, 10)],
    ['Plan', 'Source', source],
    ['Plan', 'Duration', formatYears(planYears(plan))],
    ['Inputs', 'Initial principal (THB)', plan.principal],
    ...plan.phases.map((phase, index): (string | number)[] => [
      'Inputs',
      `Phase ${index + 1} (${stageName(index)})`,
      `${phase.years} years x ${phase.monthlyDca} THB/month`,
    ]),
    ...plan.assets.map((asset): (string | number)[] => [
      'Inputs',
      `Dividend yield % per year: ${ASSET_BY_ID.get(asset.assetId)?.ticker ?? asset.assetId}`,
      asset.dividendPct,
    ]),
    ['Estimate', 'Total DCA (THB)', Math.round(output.totalDca)],
    ['Estimate', 'Total invested capital (THB)', Math.round(output.totalInvested)],
    ['Estimate', 'Expected dividends, reinvested (THB)', Math.round(output.dividends)],
    ['Estimate', 'Total estimated value (THB)', output.total],
    ['Estimate', 'Increase vs invested capital (%)', Number(output.increasePct.toFixed(1))],
  ]
  return `${CSV_BOM}${rows.map((row) => row.map(cell).join(',')).join('\r\n')}\r\n`
}

export function exportPlanCsv(plan: CalcPlan, source: string, output: CalcOutput) {
  downloadCsv(planFilename(plan.name, 'csv'), buildPlanCsv(plan, source, output))
}

// สีอ่านจาก token (CSS variable) ใน runtime ไม่ใส่ hex ในโค้ด
const token = (name: string) => getComputedStyle(document.documentElement).getPropertyValue(`--color-${name}`).trim()

/** ส่งออกเป็นรูป PNG (วาดบน canvas ฝั่งเครื่อง ไม่ส่งข้อมูลออกนอกแอป) */
export async function exportPlanImage(plan: CalcPlan, source: string, output: CalcOutput) {
  const scale = 2
  const width = 1200
  const height = 720
  // รอให้ฟอนต์ที่ติดมากับแอปโหลดก่อนวาด (ไม่งั้นจะได้ฟอนต์สำรอง)
  await Promise.all(['700 56px Montserrat', '600 20px Montserrat', '400 20px Montserrat'].map((font) => document.fonts.load(font)))

  const canvas = document.createElement('canvas')
  canvas.width = width * scale
  canvas.height = height * scale
  const ctx = canvas.getContext('2d')
  if (!ctx) throw new Error('Could not create the image. Please try again.')
  ctx.scale(scale, scale)

  const family = 'Montserrat, "IBM Plex Sans Thai", system-ui, sans-serif'
  const text = (value: string, x: number, y: number, font: string, color: string, align: CanvasTextAlign = 'left') => {
    ctx.font = `${font} ${family}`
    ctx.fillStyle = color
    ctx.textAlign = align
    ctx.fillText(value, x, y)
  }

  ctx.fillStyle = token('paper')
  ctx.fillRect(0, 0, width, height)
  ctx.fillStyle = token('surface')
  ctx.beginPath()
  ctx.roundRect(40, 40, width - 80, height - 80, 32)
  ctx.fill()

  const left = 88
  const right = width - 88
  text('WHALE TRADE JOURNAL · SAVED PLAN', left, 104, '600 14px', token('text-muted'))
  text(plan.name, left, 160, '700 40px', token('navy-900'))
  text(`${source} · ${formatYears(planYears(plan))}`, left, 192, '400 18px', token('navy-700'))

  text('EXPECTED AMOUNT AT THE END', left, 252, '600 13px', token('text-muted'))
  text(`${formatBaht(output.total)} THB`, left, 316, '700 56px', token('navy-900'))
  text(
    `+${formatBaht(output.dividends)} THB (+${formatPercent(output.increasePct)}) generated by dividend compounding`,
    left,
    352,
    '400 18px',
    token('navy-700'),
  )

  // แถบสัดส่วน
  const barY = 392
  const barWidth = right - left
  const parts: [number, string][] = [
    [output.shares.principal, token('blue-200')],
    [output.shares.dca, token('blue-500')],
    [output.shares.dividends, token('green-500')],
  ]
  ctx.save()
  ctx.beginPath()
  ctx.roundRect(left, barY, barWidth, 14, 7)
  ctx.clip()
  ctx.fillStyle = token('blue-100')
  ctx.fillRect(left, barY, barWidth, 14)
  let cursor = left
  for (const [share, color] of parts) {
    ctx.fillStyle = color
    ctx.fillRect(cursor, barY, (share / 100) * barWidth, 14)
    cursor += (share / 100) * barWidth
  }
  ctx.restore()

  const rows: [string, string][] = [
    ['Initial principal', `${formatBaht(plan.principal)} THB`],
    ...plan.phases.map((phase, index): [string, string] => [
      `DCA — Phase ${index + 1} (${formatYears(phase.years)} × ${formatBaht(phase.monthlyDca)} THB/month)`,
      `${formatBaht(output.phaseTotals[index] ?? 0)} THB`,
    ]),
    ['Expected dividends (reinvested)', `+${formatBaht(output.dividends)} THB`],
  ]
  rows.forEach(([label, value], index) => {
    const y = 452 + index * 34
    text(label, left, y, '400 18px', token('navy-900'))
    text(value, right, y, '600 18px', token('navy-900'), 'right')
  })
  const totalY = 452 + rows.length * 34 + 14
  ctx.fillStyle = token('line')
  ctx.fillRect(left, totalY - 28, barWidth, 2)
  text('Total Estimated Value', left, totalY + 8, '700 20px', token('navy-900'))
  text(`${formatBaht(output.total)} THB`, right, totalY + 8, '700 24px', token('navy-700'), 'right')

  text(
    'An illustrative model, not a forecast or guarantee of actual investment returns.',
    left,
    height - 76,
    '400 13px',
    token('text-muted'),
  )

  const blob = await new Promise<Blob | null>((resolve) => canvas.toBlob(resolve, 'image/png'))
  if (!blob) throw new Error('Could not create the image. Please try again.')
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = planFilename(plan.name, 'png')
  document.body.appendChild(link)
  link.click()
  link.remove()
  URL.revokeObjectURL(url)
}
